/** Normalize one record produced by AwsConnector.listEvents (CloudTrail JSON or a plain CloudWatch Logs line). */
export function normalizeAwsRecord(raw: unknown, ctx: { accountId: string; region: string | null; sourceType: string }): CanonicalEvent {
  const r = raw as any;
  if (r?.__cwl) {
    return {
      cloudProvider: "aws", projectOrAccountReference: ctx.accountId, region: ctx.region,
      sourceType: ctx.sourceType, sourceName: r.logGroup ?? null, eventTimestamp: new Date(r.timestamp).toISOString(),
      resourceType: "cloudwatch_log_group", resourceId: r.logGroup ?? null, serviceName: null, severity: null,
      principal: null, sourceIp: null, destinationIp: null, action: null, status: null, httpStatus: null, httpMethod: null,
      urlPath: null, userAgent: null, traceId: null, requestId: null, normalizedEventType: "app.log", categories: ["app.log"],
      providerEventId: r.eventId ?? null, normalized: { message: String(r.message ?? "").slice(0, 8000) },
    };
  }
  return normalizeCloudTrail(r as CloudTrailRecord, { accountId: ctx.accountId, sourceType: ctx.sourceType });
}

export interface AwsConnectionConfig {
  accountId: string;
  roleArn: string;
  /** Unique per connection, generated by Vigil, stored in the secret store, required by the role trust policy. */
  externalId: string;
  regions: string[];
  sessionName?: string;
}

/**
 * Cross-account, read-only AWS connector. Uses STS AssumeRole with ExternalId to obtain
 * 1-hour temporary credentials; never accepts long-lived access keys.
 */
export class AwsConnector implements CloudConnector {
  readonly provider = "aws" as const;
  private creds: { accessKeyId: string; secretAccessKey: string; sessionToken: string; expiration: Date } | null = null;

  constructor(private readonly cfg: AwsConnectionConfig, private readonly checkpoints?: CheckpointStore, private readonly sts = new STSClient({ region: cfg.regions[0] ?? "us-east-1" })) {
    if (!/^\d{12}$/.test(cfg.accountId)) throw new Error("invalid AWS account id");
    if (!/^arn:aws(-[a-z]+)?:iam::\d{12}:role\/[\w+=,.@\/-]+$/.test(cfg.roleArn)) throw new Error("invalid role ARN");
    if (!cfg.externalId || cfg.externalId.length < 16) throw new Error("ExternalId required (≥16 chars)");
  }

  async connect(): Promise<void> {
    if (this.creds && this.creds.expiration.getTime() - Date.now() > 5 * 60_000) return;
    const out = await withRetry(() => this.sts.send(new AssumeRoleCommand({
      RoleArn: this.cfg.roleArn, ExternalId: this.cfg.externalId,
      RoleSessionName: this.cfg.sessionName ?? "vigil-reader", DurationSeconds: 3600,
    })));
    const c = out.Credentials;
    if (!c?.AccessKeyId || !c.SecretAccessKey || !c.SessionToken || !c.Expiration) throw new Error("AssumeRole returned no credentials");
    this.creds = { accessKeyId: c.AccessKeyId, secretAccessKey: c.SecretAccessKey, sessionToken: c.SessionToken, expiration: c.Expiration };
  }

  private async clientCfg(region: string) {
    await this.connect();
    return { region, credentials: { ...this.creds! } };
  }

  async testConnection(): Promise<ConnectionTestResult> {
    const res: ConnectionTestResult = { ok: false, provider: "aws", accountRef: this.cfg.accountId, principal: null, credentialType: "sts:assume-role", checks: [], readOnly: true, warnings: [], errors: [], sampleReadOk: false, testedAt: new Date().toISOString() };
    try {
      await this.connect();
      const sts = new STSClient(await this.clientCfg(this.cfg.regions[0] ?? "us-east-1"));
      const id = await sts.send(new GetCallerIdentityCommand({}));
      res.principal = id.Arn ?? null;
      if (id.Account !== this.cfg.accountId) res.errors.push(`assumed role belongs to ${id.Account}, expected ${this.cfg.accountId}`);
    } catch (e) {
      res.errors.push(`AssumeRole failed: ${(e as Error).message}`);
      return res;
    }
    const region = this.cfg.regions[0] ?? "us-east-1";
    try {
      const ct = new CloudTrailClient(await this.clientCfg(region));
      await ct.send(new LookupEventsCommand({ MaxResults: 1, StartTime: new Date(Date.now() - 86_400_000), EndTime: new Date() }));
      res.checks.push({ permission: "cloudtrail:LookupEvents", granted: true, required: true });
      res.sampleReadOk = true;
    } catch (e) {
      res.checks.push({ permission: "cloudtrail:LookupEvents", granted: false, required: true });
      res.errors.push(`cloudtrail:LookupEvents: ${(e as Error).message}`);
    }
    try {
      const cw = new CloudWatchLogsClient(await this.clientCfg(region));
      await cw.send(new DescribeLogGroupsCommand({ limit: 1 }));
      res.checks.push({ permission: "logs:DescribeLogGroups", granted: true, required: false });
    } catch {
      res.checks.push({ permission: "logs:DescribeLogGroups", granted: false, required: false });
      res.warnings.push("CloudWatch Logs not readable — optional");
    }
    res.warnings.push("Write-permission probing for AWS uses iam:SimulatePrincipalPolicy, which needs extra rights; verify the role only has SecurityAudit/ViewOnlyAccess-style policies.");
    res.ok = res.sampleReadOk && res.errors.length === 0;
    return res;
  }

  async discoverSources(): Promise<DiscoveredSource[]> {
    const out: DiscoveredSource[] = [
      { sourceType: "aws_cloudtrail_management", name: "CloudTrail management events", filter: null, description: "LookupEvents API (90-day management event history)", available: true, recommended: true },
      { sourceType: "aws_guardduty", name: "GuardDuty findings", filter: null, description: "Planned (Increment 6)", available: false, recommended: true },
      { sourceType: "aws_securityhub", name: "Security Hub findings", filter: null, description: "Planned (Increment 6)", available: false, recommended: true },
      { sourceType: "aws_vpc_flow", name: "VPC Flow Logs (CloudWatch)", filter: null, description: "Planned", available: false, recommended: false },
    ];
    try {
      const cw = new CloudWatchLogsClient(await this.clientCfg(this.cfg.regions[0] ?? "us-east-1"));
      const groups = await cw.send(new DescribeLogGroupsCommand({ limit: 50 }));
      for (const g of groups.logGroups ?? []) {
        out.push({ sourceType: "aws_cloudwatch_logs", name: g.logGroupName!, filter: null, description: "CloudWatch log group", available: true, recommended: false, meta: { logGroupName: g.logGroupName } });
      }
    } catch { /* optional */ }
    return out;
  }

  async listEvents(q: ListEventsQuery): Promise<EventPage> {
    const region = this.cfg.regions[0] ?? "us-east-1";
    if (q.sourceType === "aws_cloudtrail_management") {
      const ct = new CloudTrailClient(await this.clientCfg(region));
      const out = await withRetry(() => ct.send(new LookupEventsCommand({ StartTime: q.start, EndTime: q.end, NextToken: q.pageToken ?? undefined, MaxResults: Math.min(q.pageSize ?? 50, 50) })));
      const raw = (out.Events ?? []).map((e) => { try { return JSON.parse(e.CloudTrailEvent ?? "{}"); } catch { return null; } }).filter(Boolean);
      return { raw, nextPageToken: out.NextToken ?? null };
    }
    if (q.sourceType === "aws_cloudwatch_logs") {
      const cw = new CloudWatchLogsClient(await this.clientCfg(region));
      const out = await withRetry(() => cw.send(new FilterLogEventsCommand({ logGroupName: q.filter ?? undefined, startTime: q.start.getTime(), endTime: q.end.getTime(), nextToken: q.pageToken ?? undefined, limit: 1000 })));
      const raw = (out.events ?? []).map((e) => { try { const j = JSON.parse(e.message ?? ""); if (j?.eventVersion && j?.eventID) return j; } catch { /* plain text */ } return { __cwl: true, logGroup: q.filter, eventId: e.eventId, timestamp: e.timestamp, message: e.message }; });
      return { raw, nextPageToken: out.nextToken ?? null };
    }
    throw new Error(`source type ${q.sourceType} not implemented for AWS`);
  }

  normalize(raw: unknown, sourceType: string): CanonicalEvent {
    return normalizeAwsRecord(raw, { accountId: this.cfg.accountId, region: this.cfg.regions[0] ?? null, sourceType });
  }

  async getCheckpoint(sourceId: string) { return this.checkpoints?.get(sourceId) ?? null; }
  async saveCheckpoint(sourceId: string, cp: { watermark: string | null; pageToken: string | null }) { await this.checkpoints?.save(sourceId, cp); }
  async disconnect() { this.creds = null; }

  /** IAM trust + permissions policy the customer applies (shown in onboarding). */
  static onboardingPolicies(vigilPrincipalArn: string, externalId: string) {
    return {
      trustPolicy: {
        Version: "2012-10-17",
        Statement: [{ Effect: "Allow", Principal: { AWS: vigilPrincipalArn }, Action: "sts:AssumeRole", Condition: { StringEquals: { "sts:ExternalId": externalId } } }],
      },
      permissionsPolicy: {
        Version: "2012-10-17",
        Statement: [{
          Effect: "Allow",
          Action: ["cloudtrail:LookupEvents", "cloudtrail:DescribeTrails", "cloudtrail:GetTrailStatus", "logs:DescribeLogGroups", "logs:FilterLogEvents", "guardduty:ListDetectors", "guardduty:ListFindings", "guardduty:GetFindings", "securityhub:GetFindings"],
          Resource: "*",
        }],
      },
    };
  }
}

// ---------- registry definition ----------

const AwsConfigSchema = z.object({
  accountId: z.string().regex(/^\d{12}$/).meta({ title: "AWS account ID" }),
  roleArn: z.string().regex(/^arn:aws(-[a-z]+)?:iam::\d{12}:role\/[\w+=,.@\/-]+$/).meta({ title: "Role ARN to assume", ui: { placeholder: "arn:aws:iam::123456789012:role/vigil-reader" } }),
  regions: z.array(z.string().regex(/^[a-z]{2}(-gov)?-[a-z]+-\d$/)).min(1).max(20).default(["us-east-1"]).meta({ title: "Regions", ui: { kind: "list" } }),
});
type AwsConfig = z.infer<typeof AwsConfigSchema>;

export const awsConnectorDefinition: ConnectorDefinition<AwsConfig, never> = {
  id: "aws", kind: "cloud", displayName: "Amazon Web Services", version: "1.0.0",
  description: "CloudTrail management events and CloudWatch Logs via a cross-account read-only role.",
  configSchema: AwsConfigSchema,
  credentialSchema: null,
  authModes: [{ id: "sts:assume-role", label: "STS AssumeRole + ExternalId", description: "1-hour temporary credentials; no access keys" }],
  authModeOf: () => "sts:assume-role",
  accountRefOf: (c) => c.accountId,
  // ExternalId is generated by Vigil, unique per connection. Stored raw (historical format).
  prepareSecrets: () => ({ externalId: `vigil-${randomBytes(18).toString("hex")}` }),
  encodeSecrets: (s) => (s as { externalId: string }).externalId,
  decodeSecrets: (stored) => ({ externalId: stored }),
  create(c, secrets, cps) {
    if (!secrets?.externalId) throw new Error("AWS ExternalId missing");
    return new AwsConnector({ accountId: c.accountId, roleArn: c.roleArn, externalId: secrets.externalId, regions: c.regions ?? ["us-east-1"] }, cps);
  },
  knownSources: () => [
    { sourceType: "aws_cloudtrail_management", name: "CloudTrail management events", filter: null, description: "LookupEvents API (90-day management event history)", recommended: true },
  ],
  normalizers: { "*": (raw, ctx) => normalizeAwsRecord(raw, { accountId: ctx.config.accountId, region: ctx.config.regions?.[0] ?? null, sourceType: ctx.sourceType }) },
  onboardingInstructions: (_c, secrets, rt) => AwsConnector.onboardingPolicies(rt.env.VIGIL_AWS_PRINCIPAL_ARN ?? "arn:aws:iam::<VIGIL_ACCOUNT_ID>:role/vigil-connector", secrets.externalId),
  auditSourcePrefixes: ["aws_cloudtrail"],
  formHelp: "Vigil generates a unique ExternalId and uses STS AssumeRole for 1-hour credentials. No access keys.",
};
