#!/usr/bin/env python3
"""Generate the configuration reference in docs/SELF_HOSTING.md from deploy/env.template.

The comment lines directly above each KEY=value (back to the previous blank line, setting or section header) are its
description; `# --- name ---` lines start a section. The table replaces the text between the BEGIN/END markers, so the
docs cannot drift from the template.

  python3 deploy/release/gen-env-docs.py           # rewrite docs/SELF_HOSTING.md
  python3 deploy/release/gen-env-docs.py --check   # exit 1 if the docs are stale (CI)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / "deploy" / "env.template"
DOC = ROOT / "docs" / "SELF_HOSTING.md"
BEGIN = "<!-- BEGIN ENV REFERENCE (generated by deploy/release/gen-env-docs.py from deploy/env.template; do not edit) -->"
END = "<!-- END ENV REFERENCE -->"
SECTION = re.compile(r"^#\s*---\s*(.+?)\s*---\s*$")
SETTING = re.compile(r"^([A-Z0-9_]+)=(.*)$")


def esc(s: str) -> str:
    return s.replace("|", "\\|")


def render() -> str:
    rows: list[tuple[str, str, str, str]] = []
    section, comments, intro_done = "General", [], False
    for raw in TEMPLATE.read_text().splitlines():
        line = raw.rstrip()
        if not line:
            comments = []
            intro_done = True
            continue
        m = SECTION.match(line)
        if m:
            section, comments, intro_done = m.group(1)[:1].upper() + m.group(1)[1:], [], True
            continue
        if line.startswith("#"):
            if intro_done:
                comments.append(line.lstrip("#").strip())
            continue
        m = SETTING.match(line)
        if not m:
            raise SystemExit(f"unparseable line in env.template: {line!r}")
        key, val = m.groups()
        if val.startswith("__GENERATE"):
            default = "*generated at install (secret)*"
        elif val == "":
            default = "*(empty)*"
        else:
            default = f"`{val}`"
        rows.append((section, key, default, " ".join(comments)))
        comments = []
    out = [BEGIN, "", "| Section | Variable | Default | Description |", "|---|---|---|---|"]
    for section, key, default, desc in rows:
        out.append(f"| {esc(section)} | `{key}` | {default} | {esc(desc) or '—'} |")
    out += ["", END]
    return "\n".join(out)


def main() -> int:
    doc = DOC.read_text()
    if BEGIN not in doc or END not in doc:
        print(f"markers missing in {DOC}", file=sys.stderr)
        return 1
    new = doc[: doc.index(BEGIN)] + render() + doc[doc.index(END) + len(END):]
    if "--check" in sys.argv:
        if new != doc:
            print("docs/SELF_HOSTING.md configuration reference is stale: run python3 deploy/release/gen-env-docs.py", file=sys.stderr)
            return 1
        print("configuration reference up to date")
        return 0
    DOC.write_text(new)
    print(f"updated {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
